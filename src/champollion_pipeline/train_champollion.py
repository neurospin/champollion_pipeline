#!/usr/bin/env python3
"""
Wrapper script to train a champollion_V1 self-supervised encoder for a sulcal region.
Invokes champollion/train.py via subprocess with Hydra overrides built from
pipeline-style paths. Requires dataset configs generated by generate_champollion_config.py.
"""

import csv
import logging
import os
import re
from collections.abc import Callable
from datetime import datetime
from os.path import abspath, basename, dirname, exists, isdir, join
from pathlib import Path

import numpy as np
import yaml
from champollion_utils.script_builder import ScriptBuilder
from tensorboard.backend.event_processing.event_file_loader import EventFileLoader
from tensorboard.util.tensor_util import make_ndarray

from champollion_pipeline.derivatives_layout import (
    compute_champollion_configs_root,
    compute_run_log_derivatives_dir,
    compute_run_log_path,
)
from champollion_pipeline.models.checkpoint import DEFAULT_CHECKPOINT_EPOCH, has_region_weights
from champollion_pipeline.process_setup import init_pipeline_process
from champollion_pipeline.utils.qc_report import (
    ID_COLUMN,
    QC_COLUMN,
    REASON_COLUMN,
    fetch_crop_qc_rows,
    read_crop_subjects,
    read_qc_tsv,
    write_qc_tsv,
    write_run_qc_tsv,
)

logger = logging.getLogger(__name__)

_SCRIPT_DIR = dirname(abspath(__file__))
_CONTRASTIVE_DIR = abspath(join(_SCRIPT_DIR, "..", "..", "external", "champollion_V1", "champollion"))
_PIPELINE_DATA_DIR = abspath(join(_SCRIPT_DIR, "..", "..", "data"))
_SWF_UNSUPPORTED_MESSAGE = (
    "--swf is not supported yet by train_champollion: soma-workflow submission "
    "for training is not implemented. Re-run without --swf to train locally, "
    "or submit the command through a cluster scheduler script."
)

# Hydra 1.3 override grammar: a value made only of these characters, holding a "/",
# parses back to itself unquoted (never as an int, float, bool or null).
_HYDRA_BARE_VALUE = re.compile(r"[A-Za-z0-9_./:+-]*/[A-Za-z0-9_./:+-]*")
_HYDRA_QUOTE_BACKSLASHES = re.compile(r"(\\+)(?='|\Z)")
_HYDRA_INTERPOLATION_OPEN = "${"

INPUT_QC_FILE = "input_qc.tsv"
INPUT_QC_KINDS = ("foldlabel", "mask")
FAILED_STATUS = 1
_AUGMENTATIONS_GROUP = "augmentations"
_AUGMENTATIONS_SETTING = "apply_augmentations"
_DATASET_FOLDER_REFERENCE = "${dataset_folder}"
_FOLDLABEL_ARRAY = re.compile(r"([LR])label\.npy")


def _encode_hydra_value(value: str) -> str:
    """Return value as Hydra 1.3 override text whose parsed value equals value. O(len)."""
    if _HYDRA_BARE_VALUE.fullmatch(value):
        return value
    # In a quoted Hydra string a backslash run is literal unless it precedes the
    # closing or an escaped quote, where each backslash must be doubled. "$" is kept.
    escaped = _HYDRA_QUOTE_BACKSLASHES.sub(lambda m: m.group(1) * 2, value).replace("'", "\\'")
    return "'" + escaped + "'"


def _refuse_hydra_interpolation(path: str, option: str) -> None:
    """Raise ValueError naming path (and option) when path contains "${". O(len)."""
    if _HYDRA_INTERPOLATION_OPEN in path:
        raise ValueError(
            f"{option} {path} contains {_HYDRA_INTERPOLATION_OPEN!r}, which Hydra 1.3 resolves as an "
            "interpolation in its run and config directories; choose a path without it."
        )


def _has_refused_report(output_dir: str) -> bool:
    """Return True when output_dir holds a readable input_qc.tsv with no qc 1 row."""
    try:
        records = read_qc_tsv(join(output_dir, INPUT_QC_FILE))
    except (OSError, ValueError, csv.Error):
        return False
    return not any(record[QC_COLUMN] == 1 for record in records)


def _report_input_qc(rows: list[dict[str, object]], report_path: str) -> int:
    """Log one ERROR per qc 0 row; return FAILED_STATUS, after one FAIL record, when no row has qc 1, else 0."""
    for row in rows:
        if row[QC_COLUMN] == 0:
            logger.error(f"input QC excluded {row[ID_COLUMN]}: {row[REASON_COLUMN]}")
    if any(row[QC_COLUMN] == 1 for row in rows):
        return 0
    logger.fail(f"no subject passed the training input QC, see {report_path}")
    return FAILED_STATUS


def _read_yaml(path: str) -> object:
    """Return the parsed YAML document at path."""
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def _resolve_dataset_path(value: str, dataset_folder: str | None) -> str:
    """Return value with its ${dataset_folder} reference replaced; ValueError when the folder is unknown."""
    if _DATASET_FOLDER_REFERENCE not in value:
        return value
    if dataset_folder is None:
        raise ValueError(f"{value}: no dataset_folder in the localization config")
    return value.replace(_DATASET_FOLDER_REFERENCE, dataset_folder)


def _find_dataset_folder(localization_yaml: str) -> str | None:
    """Return the top-level str dataset_folder of the YAML file, else None (yaml.YAMLError propagates)."""
    if not exists(localization_yaml):
        return None
    with open(localization_yaml, encoding="utf-8") as f:
        document = yaml.safe_load(f)
    folder = document.get("dataset_folder") if isinstance(document, dict) else None
    return folder if isinstance(folder, str) else None


class TrainChampollion(ScriptBuilder):
    """Script for training a champollion_V1 encoder for a sulcal region."""

    def __init__(self):
        super().__init__(
            script_name="train_champollion",
            description=(
                "Train a champollion_V1 self-supervised encoder for a sulcal region. "
                "Dataset configs must have been generated first by "
                "generate_champollion_config.py."
            ),
        )
        (
            self.add_required_argument(
                "--dataset",
                "Dataset name — must match a directory in the dataset configs search path "
                "(built-in champollion_V1 configs, or a custom directory supplied with --config-dir).",
            )
            .add_required_argument(
                "--region",
                "Region config name, e.g. 'cingulate_left'. "
                "Must correspond to a YAML file under configs/dataset/{dataset}/.",
            )
            .add_optional_argument(
                "--config-dir",
                "Root of a Hydra configs directory that takes precedence over the built-in "
                "champollion_V1 configs, which remain the fallback. Must contain "
                "dataset/{dataset}/{region}.yaml. Default: "
                "data/{dataset}/derivatives/champollion_V1/configs (where "
                "generate_champollion_config.py writes for crops under data/).",
                default=None,
            )
            .add_optional_argument(
                "--mode", "Training mode: 'encoder', 'classifier', or 'regresser'.", default="encoder"
            )
            .add_optional_argument(
                "--output_dir",
                "Directory for Hydra logs and model checkpoints. "
                "Defaults to data/{dataset}/derivatives/champollion_V1/models/{region}/.",
                default=None,
            )
            .add_optional_argument(
                "--njobs",
                "Number of CPU workers for the DataLoader (num_cpu_workers override).",
                default=None,
                type_=int,
            )
            .add_flag("--cpu", "Force CPU usage (sets CUDA_VISIBLE_DEVICES='').")
            .add_flag("--overwrite", "Re-train even if output directory already exists.")
            .add_flag(
                "--load-sparse",
                "Use sparse per-subject loading (requires coords_all in dataset config). "
                "Default: False — classic single .npy format as generated by generate_champollion_config.py.",
            )
            .add_optional_argument(
                "--localization",
                "Dataset localization preset to use (e.g. 'local', 'jean-zay'). "
                "Must match the value used in generate_champollion_config.py.",
                default="local",
            )
            .add_flag(
                "--swf",
                "Not supported yet: soma-workflow submission for training is not implemented; "
                "passing this flag makes the run fail immediately.",
            )
        )

    def _resolve_config_dir(self) -> str:
        """Return abspath(--config-dir) if given, else
        compute_champollion_configs_root(_PIPELINE_DATA_DIR, dataset). O(1)."""
        if self.args.config_dir:
            return abspath(self.args.config_dir)
        return compute_champollion_configs_root(_PIPELINE_DATA_DIR, self.args.dataset)

    def _resolve_output_dir(self):
        """Return absolute output path, defaulting to the pipeline derivatives tree."""
        if self.args.output_dir:
            return abspath(self.args.output_dir)
        return abspath(
            join(
                _SCRIPT_DIR,
                "..",
                "..",
                "data",
                self.args.dataset,
                "derivatives",
                "champollion_V1",
                "models",
                self.args.region,
            )
        )

    def _validate_inputs(self):
        """Refuse "${" in the output and config dirs, then check that the Hydra dataset config exists."""
        _refuse_hydra_interpolation(self._resolve_output_dir(), "--output_dir")
        _refuse_hydra_interpolation(self._resolve_config_dir(), "--config-dir")
        builtin_path = join(_CONTRASTIVE_DIR, "configs", "dataset", self.args.dataset, f"{self.args.region}.yaml")
        local_path = join(self._resolve_config_dir(), "dataset", self.args.dataset, f"{self.args.region}.yaml")
        if not exists(local_path) and not exists(builtin_path):
            raise FileNotFoundError(
                f"Dataset config not found in either location:\n"
                f"  local   : {local_path}\n"
                f"  built-in: {builtin_path}\n"
                f"Run generate_champollion_config.py --dataset {self.args.dataset} first.\n"
                f"pass --config-dir for configs elsewhere"
            )

        valid_modes = ("encoder", "classifier", "regresser")
        if self.args.mode not in valid_modes:
            raise ValueError(f"Invalid --mode '{self.args.mode}'. Choose from: {', '.join(valid_modes)}.")

    def _find_config_file(self, relative_path: str) -> str:
        """Return relative_path under the resolved config dir when present there, else under the checkout's configs."""
        local_path = join(self._resolve_config_dir(), relative_path)
        return local_path if exists(local_path) else join(_CONTRASTIVE_DIR, "configs", relative_path)

    def _is_augmented(self) -> bool:
        """Return apply_augmentations of the augmentations group of config.yaml's defaults list.

        Raises when config.yaml names no such group or the group file has no such setting.
        """
        defaults = _read_yaml(self._find_config_file("config.yaml"))["defaults"]
        group = next(
            entry[_AUGMENTATIONS_GROUP]
            for entry in defaults
            if isinstance(entry, dict) and _AUGMENTATIONS_GROUP in entry
        )
        document = _read_yaml(self._find_config_file(f"{_AUGMENTATIONS_GROUP}/{group}.yaml"))
        return bool(document[_AUGMENTATIONS_SETTING])

    def _fetch_input_qc_rows(self) -> list[dict[str, object]]:
        """Return the crop QC rows of the foldlabel_all crop folder and side, for the subjects of subjects_all."""
        region = _read_yaml(self._find_config_file(f"dataset/{self.args.dataset}/{self.args.region}.yaml"))
        dataset_folder = _find_dataset_folder(
            self._find_config_file(f"dataset_localization/{self.args.localization}.yaml")
        )
        label_array = _resolve_dataset_path(region["foldlabel_all"], dataset_folder)
        subjects_path = _resolve_dataset_path(region["subjects_all"], dataset_folder)
        side = _FOLDLABEL_ARRAY.fullmatch(basename(label_array))
        if side is None:
            raise ValueError(f"foldlabel_all {label_array} does not name a <side>label.npy file")
        crop_dir = dirname(dirname(label_array))
        return fetch_crop_qc_rows(
            dirname(crop_dir),
            [basename(crop_dir)],
            INPUT_QC_KINDS,
            read_crop_subjects(subjects_path),
            sides=(side.group(1),),
        )

    def _run_input_qc(self, output_dir: str) -> int:
        """Write output_dir/input_qc.tsv when augmentation is on; return 0 to launch train.py, else FAILED_STATUS."""
        report_path = join(output_dir, INPUT_QC_FILE)
        try:
            if not self._is_augmented():
                return 0
            rows = self._fetch_input_qc_rows()
            write_qc_tsv(report_path, rows)
        except Exception as exc:
            logger.warning(f"input QC not written: {type(exc).__name__}: {exc}", exc_info=True)
            return 0
        return _report_input_qc(rows, report_path)

    def _should_skip(self, output_dir: str) -> bool:
        """Return True when output_dir is kept: it exists, without --overwrite and without a refused report."""
        return exists(output_dir) and not self.args.overwrite and not _has_refused_report(output_dir)

    def default_log_path(self) -> str:
        """Run-log path of a bare --log: .log/training_<stamp>.log in the dataset's champollion_V1/<masks> folder."""
        return compute_run_log_path(
            compute_run_log_derivatives_dir("training", join(_PIPELINE_DATA_DIR, self.args.dataset)),
            "training",
            datetime.now().astimezone(),
        )

    def run(self):
        """Execute the training pipeline."""
        if self.args.swf:
            raise NotImplementedError(_SWF_UNSUPPORTED_MESSAGE)
        self._validate_inputs()

        local_dir = os.getcwd()
        original_cuda = os.environ.get("CUDA_VISIBLE_DEVICES")

        if self.args.cpu:
            os.environ["CUDA_VISIBLE_DEVICES"] = ""
            logger.trace("CPU mode enabled: CUDA_VISIBLE_DEVICES set to empty string")

        try:
            return self._run_training(local_dir)
        finally:
            if original_cuda is None:
                os.environ.pop("CUDA_VISIBLE_DEVICES", None)
            else:
                os.environ["CUDA_VISIBLE_DEVICES"] = original_cuda

    def _run_training(self, local_dir):
        """Run train.py from the champollion_V1 champollion package directory."""
        output_dir = self._resolve_output_dir()

        if self._should_skip(output_dir):
            logger.trace(f"Output directory already exists: {output_dir}; use --overwrite to force retraining.")
            return 0

        if _has_refused_report(output_dir):
            os.remove(join(output_dir, INPUT_QC_FILE))
        os.makedirs(output_dir, exist_ok=True)
        if self._run_input_qc(output_dir) == FAILED_STATUS:
            return FAILED_STATUS
        os.chdir(_CONTRASTIVE_DIR)
        try:
            platform = "cpu" if self.args.cpu else "cuda"

            # Hydra command-line overrides
            # +dataset/{dataset}/{region}=null appends the generated region config
            overrides = [
                f"+dataset/{self.args.dataset}={self.args.region}",
                f"+dataset_localization={self.args.localization}",
                f"platform={platform}",
                f"mode={self.args.mode}",
                "hydra.run.dir=" + _encode_hydra_value(output_dir),
            ]

            config_dir = self._resolve_config_dir()
            overrides.append("hydra.searchpath=[" + _encode_hydra_value("file://" + config_dir) + "]")
            # Explicit dataset_folder override: redundant when --config-path makes
            # config_dir Hydra's primary source (its localization YAML already wins),
            # but still needed when only hydra.searchpath applies, where the checkout's
            # localization YAML would otherwise take precedence.
            # local.yaml uses @package _global_, so dataset_folder is at the config
            # root, not nested under dataset_localization.
            local_yaml_path = join(config_dir, "dataset_localization", f"{self.args.localization}.yaml")
            dataset_folder = _find_dataset_folder(local_yaml_path)
            if dataset_folder is not None:
                overrides.append("++dataset_folder=" + _encode_hydra_value(dataset_folder))

            overrides.append(f"load_sparse={'true' if self.args.load_sparse else 'false'}")

            if self.args.njobs is not None:
                overrides.append(f"num_cpu_workers={self.args.njobs}")

            cmd = ["python3", "train.py", *overrides]
            if isdir(config_dir):
                if exists(join(config_dir, "config.yaml")):
                    logger.warning(
                        f"{join(config_dir, 'config.yaml')} replaces the champollion_V1 "
                        f"config.yaml (--config-dir is Hydra's primary config path)."
                    )
                cmd += ["--config-path", config_dir, "--config-dir", join(_CONTRASTIVE_DIR, "configs")]
            status = self.execute_command(cmd, shell=False)
        finally:
            os.chdir(local_dir)
        failed = _report_training_qc(output_dir)
        if status == 0 and failed & _TRAINING_USABILITY_CHECKS:
            return 1
        return status


TRAINING_QC_FILE = "training_qc.tsv"


def _check_weights(output_dir: str) -> str:
    """Return "" when stage 4 would find region weights in output_dir, else the reason."""
    if has_region_weights(output_dir, DEFAULT_CHECKPOINT_EPOCH):
        return ""
    return (
        "missing logs/best_model_weights.pt and logs/lightning_logs/version_*/checkpoints/"
        f"epoch={DEFAULT_CHECKPOINT_EPOCH}-step=*.ckpt"
    )


def _check_hydra_config(output_dir: str) -> str:
    """Return "" when .hydra/config.yaml is a YAML mapping, else the reason."""
    config_path = Path(output_dir, ".hydra", "config.yaml")
    if not config_path.is_file():
        return ".hydra/config.yaml missing"
    try:
        config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    except (OSError, ValueError, yaml.YAMLError):
        config = None
    return "" if isinstance(config, dict) else ".hydra/config.yaml is not a YAML mapping"


def _non_finite_loss_tags(event_file: Path) -> list[str]:
    """Return the scalar loss tags of a TensorBoard event file that hold a non-finite value."""
    tags: list[str] = []
    try:
        for event in EventFileLoader(str(event_file)).Load():
            for value in event.summary.value:
                if value.metadata.plugin_data.plugin_name != "scalars" or "loss" not in value.tag.lower():
                    continue
                if value.tag not in tags and not np.isfinite(make_ndarray(value.tensor)).all():
                    tags.append(value.tag)
    except (OSError, ValueError):
        pass
    return tags


def _check_losses(output_dir: str) -> str:
    """Return "" when no logged loss scalar is NaN or infinite, else the reason."""
    event_files = sorted(p for p in Path(output_dir, "logs").rglob("events.out.tfevents.*") if p.is_file())
    failures = []
    for event_file in event_files:
        tags = _non_finite_loss_tags(event_file)
        if tags:
            failures.append(f"{event_file.relative_to(output_dir).as_posix()} ({', '.join(tags)})")
    return "non-finite loss values in " + "; ".join(failures) if failures else ""


_TRAINING_QC_CHECKS: tuple[tuple[str, Callable[[str], str]], ...] = (
    ("weights", _check_weights),
    ("hydra_config", _check_hydra_config),
    ("losses", _check_losses),
)

# A failed member leaves a model folder stage 4 cannot load; a failed losses check stays report-only.
_TRAINING_USABILITY_CHECKS = frozenset({"weights", "hydra_config"})


def _report_training_qc(output_dir: str) -> frozenset[str]:
    """Write output_dir/training_qc.tsv, log one summary line and return the failed check names.

    Never raises an Exception: the result is empty when the report could not be built.
    """
    report_path = join(output_dir, TRAINING_QC_FILE)
    try:
        rows = []
        for name, check in _TRAINING_QC_CHECKS:
            reason = check(output_dir)
            rows.append({"check": name, "qc": 0 if reason else 1, "reason": reason})
        write_run_qc_tsv(report_path, rows)
    except Exception as exc:
        logger.warning(f"training QC not written: {type(exc).__name__}: {exc}", exc_info=True)
        return frozenset()
    failed = [row["check"] for row in rows if row["qc"] == 0]
    if failed:
        logger.warning(f"training QC failed ({', '.join(failed)}); report: {report_path}")
    else:
        logger.output(f"Training QC passed; report: {report_path}")
    return frozenset(failed)


def main():
    """Main entry point."""
    init_pipeline_process()
    script = TrainChampollion()
    return script.main()


if __name__ == "__main__":
    exit(main())
